#!/usr/bin/env node
// Requirement trace: every MUST requirement needs a test or a manual check, and every ID used must exist.
// Requirements are headings like `### R-01 [MUST] Title` in docs/REQUIREMENTS.md.
// Default (strict): only a ticked manual check `- [x] R-xx` counts.
// --listed: a listed manual check `- [ ] R-xx` counts too (used by the commit gate).
// --slice S3: only the requirements that slice covers (from docs/PLAN.md).
// --markdown: the matrix requirement | tests | commits | manual check, for docs/TRACE.md.
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { isMain } from './hook-common.mjs';
import { readRequirements, readPlan, readText, expandIds, MANUAL_CHECKS_FILE } from './scope.mjs';

const ids = (text) => new Set(text.match(/\bR-\d+\b/g) ?? []);

function testFiles(root) {
  const dir = join(root, 'tests');
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => /\.(test\.)?m?js$/.test(f));
}

function manualChecks(root) {
  const lines = readText(join(root, MANUAL_CHECKS_FILE)).split('\n');
  const passed = new Set();
  const listed = new Set();
  for (const line of lines) {
    if (/^\s*- \[x\]/i.test(line)) for (const id of ids(line)) passed.add(id);
    if (/^\s*- \[[ x]\]/i.test(line)) for (const id of ids(line)) listed.add(id);
  }
  return { passed, listed };
}

/**
 * Builds the trace. Returns rows for the MUST requirements in scope, the counts and the orphan IDs.
 * options: { root, listed, slice }
 */
export function trace(options = {}) {
  const root = options.root ?? process.cwd();
  const requirements = readRequirements(root);
  const testedBy = new Map();
  for (const file of testFiles(root)) {
    for (const id of ids(readText(join(root, 'tests', file)))) {
      testedBy.set(id, [...(testedBy.get(id) ?? []), file]);
    }
  }
  const checks = manualChecks(root);
  const counted = options.listed ? checks.listed : checks.passed;

  let inScope = requirements.filter((r) => r.scope === 'MUST');
  let sliceError = null;
  if (options.slice) {
    const plan = readPlan(root);
    const entry = plan?.get(options.slice);
    if (!entry) sliceError = `${options.slice} is not in docs/PLAN.md`;
    else inScope = inScope.filter((r) => entry.covers.includes(r.id));
  }

  const rows = inScope.map((r) => {
    const tests = testedBy.get(r.id) ?? [];
    const manual = checks.passed.has(r.id) ? 'passed' : checks.listed.has(r.id) ? 'listed' : 'none';
    const how = tests.length ? `test: ${tests.join(', ')}` : counted.has(r.id) ? `manual check ${manual}` : 'MISSING';
    return { ...r, tests, manual, how, missing: how === 'MISSING' };
  });

  const known = new Set(requirements.map((r) => r.id));
  const orphans = [...new Set([...testedBy.keys(), ...checks.listed])].filter((id) => !known.has(id));
  return {
    requirements,
    rows,
    must: rows.length,
    missing: rows.filter((r) => r.missing).length,
    orphans,
    manualListed: checks.listed.size,
    manualPassed: checks.passed.size,
    sliceError,
    ok: !sliceError && requirements.length > 0 && rows.every((r) => !r.missing) && orphans.length === 0,
  };
}

function commitsByRequirement(root) {
  let log = '';
  try {
    log = execFileSync('git', ['log', '--format=%h %s'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    return new Map();
  }
  const map = new Map();
  for (const line of log.split('\n').filter(Boolean)) {
    const [hash, ...rest] = line.split(' ');
    const subject = rest.join(' ');
    const inParens = subject.match(/\(([^)]*R-\d+[^)]*)\)\s*$/);
    for (const id of expandIds(inParens ? inParens[1] : '')) map.set(id, [...(map.get(id) ?? []), hash]);
  }
  return map;
}

export function markdown(root) {
  const result = trace({ root, listed: true });
  const commits = commitsByRequirement(root);
  const lines = [
    '# Trace: requirement to test, commit and manual check',
    '',
    `Generated by \`tools/trace.mjs --markdown\`. ${result.must} MUST, ${result.missing} missing, ${result.orphans.length} orphan IDs. Manual checks: ${result.manualListed} listed, ${result.manualPassed} passed.`,
    '',
    '| Requirement | Title | Tests | Commits | Manual check |',
    '|---|---|---|---|---|',
  ];
  for (const r of result.requirements) {
    const row = result.rows.find((x) => x.id === r.id);
    const tests = row?.tests.length ? row.tests.join(', ') : '';
    const manual = row ? row.manual : '';
    const scopeNote = r.scope === 'LATER' ? ' (LATER)' : '';
    lines.push(`| ${r.id}${scopeNote} | ${r.title} | ${tests} | ${(commits.get(r.id) ?? []).join(', ')} | ${manual} |`);
  }
  if (result.orphans.length) lines.push('', `IDs used but not defined: ${result.orphans.join(', ')}`);
  return lines.join('\n') + '\n';
}

function cli(argv) {
  const rootIdx = argv.indexOf('--root');
  const root = rootIdx >= 0 ? argv[rootIdx + 1] : process.cwd();
  const sliceIdx = argv.indexOf('--slice');
  const slice = sliceIdx >= 0 ? argv[sliceIdx + 1] : undefined;
  if (argv.includes('--markdown')) {
    process.stdout.write(markdown(root));
    return 0;
  }
  const result = trace({ root, listed: argv.includes('--listed'), slice });
  if (result.sliceError) {
    console.log(result.sliceError);
    return 1;
  }
  for (const r of result.rows) console.log(`${r.id.padEnd(6)} ${r.how.padEnd(40)} ${r.title}`);
  if (result.orphans.length) console.log(`\nIDs used but not defined: ${result.orphans.join(', ')}`);
  if (!result.requirements.length) console.log('No requirements found in docs/REQUIREMENTS.md');
  console.log(`\n${result.must} MUST, ${result.missing} missing, ${result.orphans.length} orphan IDs`);
  return result.ok ? 0 : 1;
}

if (isMain(import.meta.url)) {
  process.exit(cli(process.argv.slice(2)));
}
